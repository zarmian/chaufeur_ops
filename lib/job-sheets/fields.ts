/**
 * The labels agency sheets print, and where each one's value sits.
 *
 * This dictionary is the thing that replaces a template per agency. Booking
 * software is not very imaginative: a sheet says "Pick-up Date", "Collection
 * Date" or "Date of Travel", and there are perhaps half a dozen wordings in
 * circulation for each field. Knowing them all means a new agency's sheet
 * reads correctly the first time it arrives, which matters more here than
 * anywhere — a white-label install cannot ship a code change per customer's
 * supplier.
 *
 * Order is significant. The first alias that yields a value a parser accepts
 * wins, so the specific comes before the general: `Trip Total` before `Total`,
 * `Mb:` before `Mobile`. A label whose box is blank yields nothing and the
 * search moves on, which is why a sheet with an empty `Trip Total` and a filled
 * `Total` still finds the price.
 *
 * What is deliberately *not* here: bare `Date:` and bare `Time:`. Both appear
 * on this sample beside `Signature:` at the foot of the page, and on plenty of
 * sheets as "Booked On". A date read from the wrong box is the single most
 * expensive mistake this feature can make, so it is read only from a label that
 * says which date it means.
 *
 * That last rule is about *printed sheets*, and it is why there are two
 * dictionaries — see `MESSAGE_ALIASES`.
 */

export interface FieldAlias {
  label: string;
  placement: Placement;
  /**
   * Whether the label must begin a line or a column.
   *
   * What makes short labels safe. `PU:`, `To:` and `From:` are too common
   * inside other text to match anywhere, and too useful to leave out.
   */
  lineStart?: boolean;
  /**
   * Labels that end the part of the text this field may be read from.
   *
   * Templates are written in blocks — the passenger, then the car, then the
   * chauffeur — and the same word means different things in different blocks.
   * A real confirmation carries `Contact:` twice: once under `Passenger:`,
   * blank because nobody had the client's number, and once under
   * `CHAUFFEUR:`. Reading rightwards for a passenger's phone found the blank
   * one, moved on, and took the driver's.
   *
   * That is worse than a wrong field. `lib/tracking.ts` withholds a driver's
   * number from the passenger on purpose — a forwarded link should not leave
   * an owner-driver's mobile with a client — and this would have handed it
   * over as the passenger's own contact.
   */
  notAfter?: string[];
}

/**
 * Where the text came from, which decides how much a label can be trusted.
 *
 * A printed sheet is generated by software and carries every field it has,
 * filled or not: a blank `Date:` beside `Signature:`, a `Booked On:` next to
 * the pickup date, a whole column of charge lines nobody entered. Ambiguity is
 * the normal condition and the reader has to be strict.
 *
 * A message is typed by a person for one booking. Nobody types `Date:` and
 * means the date they typed it. The same label that is dangerous on a sheet is
 * the obvious reading in a message, so the vocabulary differs by source rather
 * than being the intersection of the two — which would be the worst of both.
 */
export type SheetSource = 'sheet' | 'message';

